const stored = (() => {
  try { return localStorage.getItem('language') } catch { return null }
})()

export const locale = ref(stored === 'en-US' ? 'en-US' : 'zh-CN')

watch(locale, value => {
  try { localStorage.setItem('language', value) } catch { /* Storage may be unavailable. */ }
  document.documentElement.lang = value
  document.title = value === 'en-US' ? 'Squirrel Downloader' : '松鼠下载器'
  dayjs.locale(value === 'en-US' ? 'en' : 'zh-cn')
}, { immediate: true })

export function t(key, params = {}) {
  const text = locale.value === 'en-US' ? translations[key] || key : key
  return text.replace(/\{(\w+)\}/g, (_, name) => String(params[name] ?? `{${name}}`))
}

export function apiError(error, fallback) {
  const detail = error.response?.data?.error
  if (locale.value === 'zh-CN') return detail || t(fallback)
  return detail && translations[detail] ? t(detail) : t(fallback)
}
